//! خريطة زمن المشغّل في الصفحة — **الصيغة الواحدة** التي يجب أن يتّفق عليها
//! قلبُ التطبيق (Rust) والإضافة (JS)، **وبوّابة النشر** التي تمنع القلب من
//! إرسال خريطة لا تصف الملف الذي سيسلّمه فعلاً.
//!
//! **لماذا وحدة مستقلّة** (م٦-ب، التصميم المعتمد في `0.2.9PLAN.md` §٩-ب):
//! الإضافة تقرأ من حالة الجسر حقلين: خريطة تُقاس بالثواني على الخط الزمني
//! الكامل للصفحة. ومسار الأغنية **يقصّ** الملف المُسلَّم فتصدق الخريطة، ومسار
//! `clip` يبني mute/duck **ويُبقي الطول** (`pipeline.rs`) ⇒ تمرير خريطة الكتم
//! إلى حقل «ما قُصّ» يجعل الثابت المؤسِّس («الخريطة مسطّحة داخل الفجوة»،
//! `check-extension-sync.cjs` §٢) **كاذباً**. فالعلاج: لا تُنشر خريطة إلا إذا
//! كان الملف الذي تُسلَّم للصفحة **مقصوصاً بها فعلاً** — وهذا ما تتحقّق منه
//! [`verified_map`] قبل أن تُكتب الحالة.
//!
//! **والمرآة**: [`map_full_to_cut`] هي نفس صيغة `mapFullToCut`
//! (`browser-extension/content.js:488`) سطراً بسطر — ولا تُعدَّل إحداهما وحدها.

/// أقصى فرق مقبول بين مجموع الخريطة وطول الملف المُسلَّم.
///
/// **من أين جاء**: ترميز mp3 يضيف حشواً بإطار (1152 عيّنة ≈ 26.1ms بالإطار
/// الواحد عند 44.1kHz)، وffmpeg يقرّب إلى إطارات كاملة عند فكّ الترميز
/// وإعادة الترميز ⇒ فرق بمقدار أجزاء من عُشر الثانية ليس عطلاً. و0.25 ث
/// **أعلى بمرتبة** من هذا الحشو و**أدنى بمرتبة** من أقصر فجوة يمكن للكاشف أن
/// ينتجها (800ms — قرار المالك §١٧/٣) ⇒ لا تُخفي الخريطة الكاذبة ولا ترفض
/// الخريطة الصادقة.
pub const MAP_TOLERANCE_SECS: f64 = 0.25;

/// الخط الزمني الكامل (للصفحة) ⟶ الخط الزمني المقصوص (للملف المُسلَّم).
///
/// **مرآة حرفية** لـ`mapFullToCut` في `browser-extension/content.js:488`:
/// بلا خريطة ⇒ هوية؛ وكل زوج لا يتقدّم بترتيب تصاعدي يُتجاهل، وكل ما بعد
/// الفجوة يُتراكم بمقدار ما بقي من المقاطع المحفوظة حتى `t`.
pub fn map_full_to_cut(t: f64, kept: &[(f64, f64)]) -> f64 {
    if kept.is_empty() {
        return t;
    }
    let mut acc = 0.0f64;
    for &(a, b) in kept {
        // `if (!(b > a)) continue;` في JS — ونصّها يشمل NaN (فزوج فيه NaN
        // يُتجاهل). و`partial_cmp` صراحةً هي نفس الدلالة بلا `!(x > y)` التي
        // يعدّها clippy موضعاً جديداً فوق خطّ الأساس.
        if b.partial_cmp(&a) != Some(std::cmp::Ordering::Greater) {
            continue;
        }
        if t <= a {
            break;
        }
        acc += t.min(b) - a;
    }
    acc
}

/// مجموع أطوال المقاطع المحفوظة — الطول الذي **يجب** أن يكون عليه الملف
/// المقصوص بهذه الخريطة.
///
/// **وهي قياس للخريطة لا قرار مشغّل**: لذلك لا تدخل في دعوى «تكافؤ الهوية»
/// (خريطة `[[0,D]]` تعطي `D` وخريطة فارغة تعطي `0` — وهذا صحيح ومقصود: الأولى
/// تقول «الملف بطول D»، والثانية تقول «لا خريطة»؛ وانظر اختبارات هذه الوحدة).
pub fn kept_sum(kept: &[(f64, f64)]) -> f64 {
    if kept.is_empty() {
        return 0.0;
    }
    map_full_to_cut(f64::INFINITY, kept)
}

/// هل الخريطة **هي الهوية**؟ أي: لا تحذف شيئاً من الخط الزمني الكامل.
///
/// الخريطة الفارغة والهوية سواء عند المشغّل (`mapFullToCut` بلا خريطة = هوية)،
/// ولذلك تُعامَلان معاملة واحدة عند النشر.
///
/// * `full_secs` = طول الأصل **قبل** القص (لا طول الملف المُسلَّم): الفرق بينه
///   وبين [`kept_sum`] هو ما حُذف فعلاً.
pub fn is_identity(kept: &[(f64, f64)], full_secs: f64) -> bool {
    if kept.is_empty() {
        return true;
    }
    full_secs > 0.0 && (full_secs - kept_sum(kept)).abs() <= MAP_TOLERANCE_SECS
}

/// هل الخريطة مُحكمة البناء: كل مقطع متقدّم، والكل تصاعدي غير متقاطع؟
fn well_formed(kept: &[(f64, f64)]) -> bool {
    kept.iter()
        .all(|(a, b)| a.is_finite() && b.is_finite() && b > a && *a >= 0.0)
        && kept.windows(2).all(|w| w[1].0 >= w[0].1 - 1e-9)
}

/// **بوّابة النشر**: لا تُسلَّم خريطة إلى المشغّل إلا إذا وصفت الملف المُسلَّم.
///
/// تُعيد الخريطة كما هي إن صحّت، و**فارغة** إن لم تصحّ — والفراغ عند المشغّل
/// يعني «هوية» (`mapFullToCut`)، أي سلوك اليوم بالضبط بلا تخطٍّ خاطئ. فالفشل
/// هنا **آمن**: يفقد المستخدم التخطّي ولا يفقد المزامنة.
///
/// والفحوص الثلاثة:
/// 1. **مُحكمة البناء** ([`well_formed`]): مقاطع متقدّمة غير متقاطعة.
/// 2. **الصيغة المشتركة تصل إلى نهاية الملف**: `map_full_to_cut(آخر حدّ)`
///    يساوي مجموع الخريطة — أي أن المشغّل يستهلك بالصيغة نفسها كل ما في الملف
///    ولا يبقى منه ذيل لا تصفه الخريطة. (وهذا هو الموضع الذي تُستعمل فيه صيغة
///    المشغّل داخل المنتج، لا في الاختبار وحده.)
/// 3. **الخريطة تصف ملفها**: `kept_sum ≈ served_secs` (فرق الترميز داخل
///    [`MAP_TOLERANCE_SECS`])، **و** `full_secs - kept_sum > MAP_TOLERANCE_SECS`
///    أي أن شيئاً حُذف فعلاً ⇒ ليست الهوية.
///
/// **وهنا يُكشف الفخّ الدلالي**: خريطة كتم على ملف **كامل الطول** تسقط في
/// الفحص الثالث (مجموعها أصغر من طول الملف المُسلَّم) ⇒ لا تُنشر، فلا يصير
/// «الثابت المؤسِّس» كاذباً.
pub fn verified_map(kept: &[(f64, f64)], served_secs: f64, full_secs: f64) -> Vec<(f64, f64)> {
    if kept.is_empty() {
        return Vec::new();
    }
    let last_end = kept.last().map(|r| r.1).unwrap_or(0.0);
    let total = kept_sum(kept);
    let formula_consumes_the_file = (map_full_to_cut(last_end, kept) - total).abs() <= 1e-9;
    let describes_the_file = served_secs > 0.0 && (total - served_secs).abs() <= MAP_TOLERANCE_SECS;
    if well_formed(kept)
        && formula_consumes_the_file
        && describes_the_file
        && !is_identity(kept, full_secs)
    {
        return kept.to_vec();
    }
    tracing::warn!(
        target: "bridge",
        "خريطة الصفحة لم تُنشر (مجموعها {total:.3}s · المُسلَّم {served_secs:.3}s · الأصل {full_secs:.3}s) — تُعامَل كهوية",
    );
    Vec::new()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// **ب١ — تكافؤ الهوية**: خريطة `[[0,D]]` ⇔ بلا خريطة، لكل دالة نقية في
    /// المسار. مُفسَده: قلب تراكم `acc` في [`map_full_to_cut`] ⇒ يسقط.
    ///
    /// والدعوى على **قرارات المشغّل** وحدها (`map_full_to_cut` · بوّابة النشر)،
    /// لا على [`kept_sum`]: فهي **قياس** للخريطة لا قرار (تعليقها فوق).
    #[test]
    fn identity_map_is_equivalent_to_no_map_for_every_player_function() {
        for d in [1.0f64, 2.0, 3.5, 60.0, 599.25] {
            let identity = [(0.0f64, d)];
            let none: [(f64, f64); 0] = [];
            // (١) الصيغة المشتركة: الموضع نفسه لكل لحظة على الخط الزمني.
            let steps = 37;
            for i in 0..=steps {
                let t = (d * i as f64 / steps as f64).min(d);
                assert_eq!(
                    map_full_to_cut(t, &identity),
                    map_full_to_cut(t, &none),
                    "خريطة الهوية غيّرت الموضع عند t={t} · D={d}"
                );
            }
            // (٢) الهوية لا تُنشر أبداً: الفراغ والفارغة مدخلان متطابقان
            // للمشغّل، فإرسال `[[0,D]]` كان سيعطّل بوّابة المدة ±2s في الإضافة
            // (شرطها «بلا خريطة»، content.js:745) بلا أي فائدة.
            assert!(is_identity(&identity, d), "[[0,{d}]] يجب أن تُقرأ هوية");
            assert!(verified_map(&identity, d, d).is_empty(), "الهوية لا تُنشر");
            assert!(verified_map(&none, d, d).is_empty(), "الفارغة تبقى فارغة");
        }
    }

    /// ضابط ب١: خريطة حقيقية (حُذف منها شيء) تُنشر كما هي، والصيغة تتقدّم
    /// داخل المقاطع المحفوظة وتكون **مسطّحة** داخل الفجوة.
    #[test]
    fn a_real_map_is_published_and_is_flat_across_a_gap() {
        // أصل 6s: حُذف [2,4) ⇒ مُسلَّم 4s.
        let kept = [(0.0f64, 2.0), (4.0, 6.0)];
        assert!((kept_sum(&kept) - 4.0).abs() < 1e-9);
        assert!(!is_identity(&kept, 6.0));
        assert_eq!(verified_map(&kept, 4.0, 6.0), kept.to_vec());
        assert!((map_full_to_cut(5.5, &kept) - 3.5).abs() < 1e-9);
        // مسطّحة داخل الفجوة: كل المواضع بين حدّي الحذف تُسقط إلى الدرزة.
        for t in [2.0f64, 2.5, 3.0, 3.999] {
            assert!(
                (map_full_to_cut(t, &kept) - 2.0).abs() < 1e-9,
                "الخريطة غير مسطّحة عند t={t}"
            );
        }
    }

    /// **ب٥ (الوجه الرقمي) — الفخّ الدلالي**: خريطة الكتم (مقاطع **موجودة
    /// ومكتومة**) على ملف كامل الطول تُرفض ولا تُنشر.
    ///
    /// مُفسَده: تمرير خريطة الكتم بدل خريطة القصّ ⇒ يسقط، ويُسمّى الثابت
    /// المنقوض: «الخريطة تصف الملف المُسلَّم».
    #[test]
    fn a_mute_map_on_a_full_length_file_is_never_published() {
        // ملف 6s مكتوم في [2,4) لكن **طوله 6s كما هو** (مسار clip).
        let mute_map = [(0.0f64, 2.0), (4.0, 6.0)];
        let served_full_length = 6.0;
        assert!(
            verified_map(&mute_map, served_full_length, served_full_length).is_empty(),
            "خريطة الكتم على ملف كامل الطول لا تُنشر — الثابت المنقوض: «الخريطة تصف الملف المُسلَّم»"
        );
        // ولو نُشرت لكان مجموعها 4s مقابل ملف بطول 6s ⇒ المشغّل يظن أنه يقرأ
        // ملفاً أقصر بـ2s فيهبط بالموضع أمام الصورة بثانيتين.
        assert!((kept_sum(&mute_map) - served_full_length).abs() > MAP_TOLERANCE_SECS);
    }

    /// **ب٣ (الوجه الرقمي)** — الخريطة تطابق ملفها: المجموع ≈ طول الملف
    /// المقصوص، وخريطة ملف آخر تُرفض.
    #[test]
    fn a_map_from_another_file_is_rejected() {
        // ملف 20s حُذف منه [5,15) ⇒ مُسلَّم 10s.
        let mine = [(0.0f64, 5.0), (15.0, 20.0)];
        assert_eq!(verified_map(&mine, 10.0, 20.0), mine.to_vec());
        // خريطة ملف آخر (حُذف منه 5s فقط) على الملف نفسه ⇒ مجموع 15s ≠ 10s.
        // وهي **مُحكمة البناء وليست هوية**، فلا يسقطها إلا فحص مطابقة الملف.
        let foreign = [(0.0f64, 15.0)];
        assert!(well_formed(&foreign) && !is_identity(&foreign, 20.0));
        assert!(
            verified_map(&foreign, 10.0, 20.0).is_empty(),
            "خريطة من ملف آخر يجب ألا تُنشر"
        );
    }

    /// مدخلات شاذّة لا تُنتج خريطة منشورة: NaN · مقطع مقلوب · تقاطع · سالب.
    #[test]
    fn malformed_maps_are_rejected() {
        let cases: Vec<Vec<(f64, f64)>> = vec![
            vec![(2.0, 2.0)],
            vec![(3.0, 1.0)],
            vec![(0.0, 4.0), (3.0, 6.0)],
            vec![(-1.0, 6.0)],
            vec![(0.0, f64::NAN)],
            vec![(0.0, f64::INFINITY)],
        ];
        for c in cases {
            assert!(
                verified_map(&c, 4.0, 6.0).is_empty(),
                "خريطة شاذّة نُشرت: {c:?}"
            );
        }
    }
}
